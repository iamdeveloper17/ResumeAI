// Fuzzy matching function
export function fuzzySearch(query: string, items: string[], max = 8): string[] {
  if (!query || query.length < 1) return [];

  const q = query.toLowerCase().trim();

  // Priority 1: Prefix matches
  const prefix = items.filter((s) => s.toLowerCase().startsWith(q));

  // Priority 2: Word-boundary matches (e.g., "react" matches "React Native")
  const wordBoundary = items.filter((s) => {
    if (prefix.includes(s)) return false;
    const words = s.toLowerCase().split(/\s+/);
    return words.some((w) => w.startsWith(q));
  });

  // Priority 3: Contains matches
  const contains = items.filter((s) => {
    if (prefix.includes(s) || wordBoundary.includes(s)) return false;
    return s.toLowerCase().includes(q);
  });

  // Priority 4: Fuzzy character match (typo tolerance)
  const fuzzy = items.filter((s) => {
    if (prefix.includes(s) || wordBoundary.includes(s) || contains.includes(s))
      return false;
    const target = s.toLowerCase();
    let i = 0;
    for (const char of q) {
      const idx = target.indexOf(char, i);
      if (idx === -1) return false;
      i = idx + 1;
    }
    return true;
  });

  return [...prefix, ...wordBoundary, ...contains, ...fuzzy].slice(0, max);
}